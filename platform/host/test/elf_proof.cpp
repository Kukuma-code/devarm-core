/*********************************************
 * platform/host/test: core/elf (ELF64 リーダ/ダンパ) の回帰ハーネス (host)
 *
 * 検証は 2 層 (実行環境は不要。ELF は実行しなければただのバイト列であり、
 * core/elf の契約は「バイト列の解釈」まで。ロード・実行の検証は welf 側=対象外):
 *   A) レイアウト: 各クラスの sizeof が Elf64 仕様のヘッダサイズに一致
 *      (static_assert)。ビットフィールド (elf_sym_ の type:4/bind:4) の LE
 *      配置は下記 B の実データ照合で検証する。
 *   B) 実データ解釈: 埋め込みの本物の ELF64 relocatable を各クラスで重ね読みし、
 *      既知の ground truth (下記の生成手順で llvm-objdump / 手動 struct 解析により
 *      確定) と一致することを確認する。ehdr の全フィールド、shstrtab 経由の
 *      section 名解決、symtab の名前/型/bind、rela の _info union 分解を含む。
 *   C) ダンプ smoke: info()/raw_data()/print_flags() を実データ + 合成値
 *      (phdr/dyn は relocatable に存在しないため合成) で呼び、クラッシュ・
 *      ハングしないことを確認する (出力内容の golden 照合はしない)。
 *
 * 埋め込み ELF (ELF_BLOB) の出自 — 再生成手順:
 *   $ printf 'extern int g;\nint f(void){ return g + 42; }\n' > blob.c
 *   $ clang -target x86_64-unknown-linux-gnu -O0 -c blob.c -o blob.o   # macOS でも ELF64 を吐ける
 *   blob.o (1096 bytes) をバイト配列化したもの。ground truth:
 *     ehdr: ET_REL / EM_X86_64 / shofs=456 / shqty=10 / shentsize=64 / strndx=1
 *     shdr: [2]=".text" (PROGBITS, ALLOC|EXECINSTR, size=18) / [9]=".symtab"
 *           (SYMTAB, entsize=24, link=1) / [3]=".rela.text" (RELA, entsize=24)
 *     sym : [3]="f" (info=0x12: FUNC+GLOBAL, shndx=2, size=18) / [4]="g" (UND)
 *     rela: 1 本 {ofs=7, type=42(R_X86_64_REX_GOTPCRELX), sym=4, addend=-4}
 *   注意: clang のバージョンで .comment 等が変わるため、再生成したら ground truth
 *   も採り直すこと (このファイルの検証値は埋め込んだバイト列に対して固定)。
 *
 * 前提: host は little-endian (macOS の x86-64/AArch64 とも LE)。BE host では
 * ELF64LSB の重ね読みは成立しない (本 proof の対象外)。
 *
 * ビルド例:
 *   clang++ -std=c++17 -Wall -Wextra -I core/include -I core/convert -I core/io \
 *     -I core/util -I core/elf -I . \
 *     platform/host/test/elf_proof.cpp core/elf/(all).cpp core/util/misc_token.cpp \
 *     core/convert/(all).cpp core/io/printf.cpp hal/io.cpp platform/host/io_host.cpp \
 *     -o elf_proof
 *********************************************/
